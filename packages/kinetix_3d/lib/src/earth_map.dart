bool _inside(List<double> poly, double lon, double lat) {
  var inside = false;
  final n = poly.length ~/ 2;
  for (var i = 0, j = n - 1; i < n; j = i++) {
    final xi = poly[i * 2], yi = poly[i * 2 + 1], xj = poly[j * 2], yj = poly[j * 2 + 1];
    if ((yi > lat) != (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/// True when the point is on land (Antarctica is everything south of 66° S).
bool isLand(double lat, double lon) {
  if (lat < -66) return true;
  for (final w in _water) {
    if (_inside(w, lon, lat)) return false;
  }
  for (final p in _land) {
    if (_inside(p, lon, lat)) return true;
  }
  return false;
}

/// ARGB colour for a point on the globe: ocean, forest, desert or ice.
int earthColor(double lat, double lon) {
  final land = isLand(lat, lon);
  if (!land) {
    if (lat > 78) return 0xFFE8F1F8; // Arctic sea ice
    // Slightly lighter shallow tropics.
    return lat.abs() < 25 ? 0xFF1E63C4 : 0xFF1B56AE;
  }
  if (lat < -62 || lat > 68 || (lon > -75 && lon < -10 && lat > 60)) return 0xFFF2F6F8; // ice and Greenland
  final desert = (lat > 15 && lat < 33 && lon > -17 && lon < 60) || // Sahara, Arabia
      (lat > -32 && lat < -19 && lon > 118 && lon < 145) || // Australian interior
      (lat > 36 && lat < 47 && lon > 55 && lon < 112) || // Central Asian steppe and Gobi
      (lat > 24 && lat < 37 && lon > -117 && lon < -103) || // North American deserts
      (lat > -30 && lat < -18 && lon > 14 && lon < 24); // Kalahari
  if (desert) return 0xFFC9A764;
  return lat.abs() < 23 ? 0xFF2E8B45 : 0xFF4C9A4E;
}
