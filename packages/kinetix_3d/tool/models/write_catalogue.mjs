// Writes lib/src/viewer/catalogue_data.dart from assets/viewer3d/models/index.json, so
// the app knows every viewer model (id, titles, subject, classes, keywords) without
// reading assets first. build_models.mjs runs it after writing the index; run it alone
// with `node write_catalogue.mjs`.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const models = join(here, '../../assets/viewer3d/models');
const out = join(here, '../../lib/src/viewer/catalogue_data.dart');
const remoteModels = join(here, '../../remote_models');
const remoteOut = join(here, '../../lib/src/viewer/remote_catalogue_data.dart');

const str = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const text = (t) => `LocalText({${['en', 'hi', 'kn'].map((l) => `'${l}': ${str(t?.[l] ?? '')}`).join(', ')}})`;

export function writeCatalogue() {
  const { models: list } = JSON.parse(readFileSync(join(models, 'index.json'), 'utf8'));
  const entries = list.map((m) => {
    const manifest = JSON.parse(readFileSync(join(models, `${m.id}.json`), 'utf8'));
    return `  ViewerModelInfo(
    id: ${str(m.id)},
    subject: ${str(m.subject)},
    title: ${text(m.title)},
    summary: ${text(m.summary)},
    classes: [${(m.classes || []).join(', ')}],
    keywords: [${(m.keywords || []).map(str).join(', ')}],
    variants: [${(manifest.variants || []).map((v) => str(v.id)).join(', ')}],
    credit: ${str(manifest.credit || '')},
  ),`;
  });
  writeFileSync(
    out,
    `// Generated by tool/models/write_catalogue.mjs from assets/viewer3d/models/index.json.
// Do not edit by hand: change the recipe and rebuild the models.
part of 'catalogue_info.dart';

const _viewerModels = <ViewerModelInfo>[
${entries.join('\n')}
];
`,
  );
  console.log(`catalogue: ${list.length} models -> lib/src/viewer/catalogue_data.dart`);
  writeRemoteCatalogue();
}

/** lib/src/viewer/remote_catalogue_data.dart: the models downloaded on first use. */
function writeRemoteCatalogue() {
  const index = join(remoteModels, 'index.json');
  const list = existsSync(index) ? JSON.parse(readFileSync(index, 'utf8')).models : [];
  const entries = list.map(
    (m) => `  RemoteModelInfo(
    id: ${str(m.id)},
    title: ${text(m.title)},
    subject: ${str(m.subject)},
    topic: ${str(m.topic || '')},
    classes: [${(m.classes || []).join(', ')}],
    url: '\${RemoteModels.defaultBase}/${m.id}.glb',
    bytes: ${m.bytes},
    license: ${str(m.license || '')},
    credit: ${str(m.credit || '')},
    keywords: [${(m.keywords || []).map(str).join(', ')}],
    viewer: true,
  ),`,
  );
  writeFileSync(
    remoteOut,
    `// Generated by tool/models/write_catalogue.mjs from remote_models/index.json.
// Do not edit by hand: change the recipe (remote: true) and rebuild the models.
part of 'remote_models.dart';

const _remoteModels = <RemoteModelInfo>[
${entries.join('\n')}
];
`,
  );
  console.log(`remote catalogue: ${list.length} models -> lib/src/viewer/remote_catalogue_data.dart`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeCatalogue();
