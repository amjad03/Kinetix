    'for pass = 0 to n-2',
    '  swapped = false',
    '  for j = 0 to n-2-pass',
    '    if a[j+1] < a[j]',
    '      swap a[j], a[j+1]; swapped = true',
    '  a[n-1-pass] is in place',
    '  if not swapped: stop',
    'sorted',
  ], {'sortStart': 0, 'compare': 3, 'swap': 4, 'inPlace': 5, 'noSwaps': 6, 'sortDone': 7}),
  AlgoKind.insertion => const Pseudocode([
