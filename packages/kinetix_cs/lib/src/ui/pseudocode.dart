    'for v = min to max:',
    '  repeat count[v] times: a[i] = v; i = i+1',
    'sorted',
  ], {'countStart': 0, 'countOne': 1, 'countWrite': 4, 'countDone': 5}),
  AlgoKind.linear => const Pseudocode([
    'for i = 0 to n-1',
    '  if a[i] == x',
    '    return i',
    'return not found',
  ], {'linearStart': 0, 'compare': 1, 'found': 2, 'notFound': 3}),
  AlgoKind.binary => const Pseudocode([
