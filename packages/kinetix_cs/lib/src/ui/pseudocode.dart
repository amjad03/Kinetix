    '  mergeSort(a, lo, mid); mergeSort(a, mid, hi)',
    '  merge: take the smaller front item',
    '  copy what is left of either half',
    'sorted',
  ], {'sortStart': 0, 'split': 2, 'mergeTake': 4, 'merged': 5, 'sortDone': 6}),
  AlgoKind.quick => const Pseudocode([
    'quickSort(a, lo, hi):',
    '  pivot = a[hi]; i = lo',
    '  for j = lo to hi-1',
    '    if a[j] < pivot',
    '      swap a[i], a[j]; i = i+1',
    '  swap a[i], a[hi]   // pivot in place',
    '  quickSort(a, lo, i-1); quickSort(a, i+1, hi)',
    'sorted',
  ], {'sortStart': 0, 'pivot': 1, 'compare': 3, 'swap': 4, 'pivotPlaced': 5, 'sortDone': 7}),
  AlgoKind.heap => const Pseudocode([
    'buildMaxHeap(a)',
    'for end = n-1 down to 1',
    '  swap a[0], a[end]',
