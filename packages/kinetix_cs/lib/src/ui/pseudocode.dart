    'sorted',
  ], {'sortStart': 0, 'pickKey': 1, 'compare': 2, 'swap': 3, 'sortDone': 4}),
  AlgoKind.selection => const Pseudocode([
    'for i = 0 to n-2',
    '  min = i',
    '  for j = i+1 to n-1',
    '    if a[j] < a[min]',
    '      min = j',
    '  swap a[i], a[min]',
