  AlgoKind.queue => const Pseudocode([
    'enqueue(x):',
    '  if rear == MAX-1: overflow',
    '  rear = rear+1; q[rear] = x',
    'dequeue():',
    '  if front > rear: underflow',
    '  x = q[front]; front = front+1',
