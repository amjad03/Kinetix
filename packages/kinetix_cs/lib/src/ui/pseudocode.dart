    'dequeue():',
    '  if count == 0: underflow',
    '  x = q[front]',
    '  front = (front + 1) mod n; count--',
    'peek(): return q[front]',
  ], {'cqFull': 1, 'cqEnqueue': 2, 'underflow': 4, 'dequeue': 5, 'cqFront': 6, 'peek': 7}),
  AlgoKind.list => const Pseudocode([
    'insertHead(x): node.next = head; head = node',
    'cur = head; while needed: cur = cur.next',
    'insertTail(x): cur.next = node',
    'insertAt(x, i): node.next = cur.next; cur.next = node',
    'delete(x): prev.next = cur.next',
    'search(x): if cur.data == x: found',
    'not found',
  ], {'insertHead': 0, 'walk': 1, 'insertTail': 2, 'insertAt': 3, 'unlink': 4, 'deleted': 4, 'found': 5, 'notFound': 6}),
  AlgoKind.hash => const Pseudocode([
    'h = k mod m',
    'chaining: append k to the list at h',
    'probing: if slot is free: put k there',
    '  else try the next slot: (h + i) or (h + i²) mod m',
    'no free slot: table full',
  ], {'hashStart': 0, 'hash': 0, 'chain': 1, 'placed': 2, 'collision': 3, 'tableFull': 4}),
  AlgoKind.bst => const Pseudocode([
    'insert(x): if tree empty: root = x',
    '  compare x with node; go left if smaller, right if larger',
    '  attach x as a new leaf',
    'delete(x): a leaf is removed',
