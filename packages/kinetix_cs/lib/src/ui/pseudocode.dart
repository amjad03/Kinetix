import '../algo/frames.dart';
import 'algo_player.dart';

/// An algorithm's pseudocode (in English, as in the textbooks) and which line each step's
/// sentence belongs to, so the player can light up the line being run.
class Pseudocode {
  const Pseudocode(this.lines, this.lineOf);

  final List<String> lines;

  /// Say key → line index.
  final Map<String, int> lineOf;

  int? lineFor(AlgoFrame f) => lineOf[f.say.key];
}

