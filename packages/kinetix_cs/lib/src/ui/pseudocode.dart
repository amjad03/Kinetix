    'while queue not empty:',
    '  u = dequeue(); visit u',
    '  for each neighbour v of u:',
    '    if v not marked: mark v; enqueue(v)',
    'done',
  ], {'bfsStart': 0, 'visitNode': 2, 'discover': 4, 'order': 5}),
  AlgoKind.dfs => const Pseudocode([
    'dfs(u):',
    '  mark u; visit u',
    '  for each neighbour v of u:',
    '    if v not marked: dfs(v)',
    '  return (back to the caller)',
