  ], {'binaryStart': 0, 'compare': 2, 'found': 3, 'goRight': 4, 'goLeft': 5, 'notFound': 6}),
  AlgoKind.stack => const Pseudocode([
    'push(x):',
    '  if top == MAX-1: overflow',
    '  top = top+1; s[top] = x',
    'pop():',
    '  if top == -1: underflow',
    '  x = s[top]; top = top-1',
    'peek(): return s[top]',
