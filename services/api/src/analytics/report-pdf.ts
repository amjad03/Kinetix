import { hasIndic, IndicFonts } from '../common/pdf-fonts.js';
import type { Tone } from './xlsx.js';

/**
 * A landscape A4 table report: the institution's name and the report title on every page, the
 * filters under the title, a filled header row repeated on each page, zebra rows, right-aligned
 * numbers, tinted cells for conditional formatting, a totals row, and a footer with who generated
 * it, when, and "Page n of N". Hindi and Kannada are drawn with the embedded Noto fonts.
 */

const W = 842;
const H = 595;
const M = 30;
const ROW = 15;
const SIZE = 8;

export interface PdfColumn {
  label: string;
  align: 'left' | 'right';
}
export interface PdfCell {
  text: string;
  tone?: Tone | null;
  toneStyle?: 'fill' | 'text';
}
export interface PdfTable {
  institution: string;
  title: string;
  filters: string[];
  columns: PdfColumn[];
  rows: PdfCell[][];
  totals?: string[] | null;
  /** "Generated by … on …", and the page label with {n} and {m}. */
  footer: string;
  pageLabel: string;
  /** Shown under the table when rows were left out. */
  note?: string;
}

const TONE_RGB: Record<Tone, [number, number, number]> = { red: [0.99, 0.89, 0.88], amber: [1, 0.95, 0.78], green: [0.86, 0.99, 0.91], blue: [0.86, 0.92, 1], grey: [0.95, 0.96, 0.98] };
const TONE_INK: Record<Tone, [number, number, number]> = { red: [0.73, 0.11, 0.11], amber: [0.71, 0.33, 0.04], green: [0.08, 0.5, 0.24], blue: [0.11, 0.31, 0.85], grey: [0.28, 0.33, 0.41] };

const SWAP: Record<string, string> = { '₹': 'Rs ', '–': '-', '—': '-', '‘': "'", '’': "'", '“': '"', '”': '"', '…': '...' };
const clean = (t: string) => [...t.normalize('NFKD').replace(/[̀-ͯ]/g, '')].map((c) => SWAP[c] ?? (c.charCodeAt(0) < 256 ? c : '?')).join('');
const escape = (t: string) => t.replace(/[\\()]/g, (m) => `\\${m}`);
const latinWidth = (t: string, size: number, bold = false) => [...t].reduce((w, c) => w + size * (/[0-9]/.test(c) ? 0.556 : /[A-Z]/.test(c) ? 0.66 : /[ il.,:;'|!]/.test(c) ? 0.28 : 0.52) * (bold ? 1.05 : 1), 0);
const f = (n: number) => n.toFixed(2);

export function renderTablePdf(t: PdfTable): Buffer {
  const fonts = new IndicFonts();
  const pages: string[][] = [];
  let page: string[] = [];
  let y = 0;

  const width = (s: string, size: number, bold = false) => (hasIndic(s) ? IndicFonts.width(s, size, bold, (x) => latinWidth(clean(x), size, bold)) : latinWidth(clean(s), size, bold));
  const text = (s: string, x: number, yy: number, size: number, bold = false, ink?: [number, number, number]) => {
    const color = ink ? `${ink.map(f).join(' ')} rg ` : '';
    const reset = ink ? ' 0 g' : '';
    if (hasIndic(s)) page.push(`${color}${fonts.draw(s, x, yy, size, bold, bold ? 'F2' : 'F1', { clean, width: (x2) => latinWidth(x2, size, bold), escape })}${reset}`);
    else page.push(`${color}BT /${bold ? 'F2' : 'F1'} ${size} Tf ${f(x)} ${f(yy)} Td (${escape(clean(s))}) Tj ET${reset}`);
  };
  /** Shortens `s` to fit `max` points, with an ellipsis. */
  const fit = (s: string, max: number, size: number, bold = false) => {
    if (width(s, size, bold) <= max) return s;
    let lo = 0;
    let hi = s.length;
    while (lo < hi) {
      const mid = Math.ceil((lo + hi) / 2);
      if (width(`${s.slice(0, mid)}...`, size, bold) <= max) lo = mid;
      else hi = mid - 1;
    }
    return `${s.slice(0, lo)}...`;
  };
  const rect = (x: number, yy: number, w: number, h: number, rgb: [number, number, number]) => page.push(`q ${rgb.map(f).join(' ')} rg ${f(x)} ${f(yy)} ${f(w)} ${f(h)} re f Q`);
  const line = (x1: number, yy: number, x2: number, w = 0.5) => page.push(`q ${w} w 0.6 G ${f(x1)} ${f(yy)} m ${f(x2)} ${f(yy)} l S Q`);

  // Column widths: share of the page by the longest text in a sample of rows, with sensible bounds.
  const avail = W - 2 * M;
  const sample = t.rows.slice(0, 300);
  const want = t.columns.map((c, i) => Math.min(220, Math.max(width(c.label, SIZE, true), ...sample.map((r) => width(r[i]?.text ?? '', SIZE)), t.totals ? width(t.totals[i] ?? '', SIZE, true) : 0) + 10));
  const total = want.reduce((a, b) => a + b, 0) || 1;
  const widths = total <= avail ? want.map((w) => w * (avail / total)) : want.map((w) => Math.max(28, (w / total) * avail));
  const scale = avail / widths.reduce((a, b) => a + b, 0);
  const cols = widths.map((w) => w * scale);
  const xs = cols.map((_, i) => M + cols.slice(0, i).reduce((a, b) => a + b, 0));

  const header = (first: boolean) => {
    y = H - M;
    text(t.institution, M, y - 12, 13, true);
    text(t.title, M, y - 28, 11, true);
    y -= 34;
    if (first) {
      for (const fl of t.filters.slice(0, 6)) {
        text(fit(fl, avail, 8), M, y - 9, 8, false, [0.28, 0.33, 0.41]);
        y -= 11;
      }
    }
    y -= 6;
    rect(M, y - ROW, avail, ROW, [0.89, 0.91, 0.94]);
    t.columns.forEach((c, i) => {
      const s = fit(c.label, cols[i] - 6, SIZE, true);
      const x = c.align === 'right' ? xs[i] + cols[i] - 3 - width(s, SIZE, true) : xs[i] + 3;
      text(s, x, y - ROW + 4.5, SIZE, true);
    });
    y -= ROW;
    line(M, y, M + avail, 0.8);
  };
  const newPage = () => {
    if (page.length) pages.push(page);
    page = [];
    header(pages.length === 0);
  };

  newPage();
  t.rows.forEach((r, ri) => {
    if (y - ROW < M + 20) newPage();
    if (ri % 2 === 1) rect(M, y - ROW, avail, ROW, [0.98, 0.98, 0.99]);
    r.forEach((c, i) => {
      if (c.tone && c.toneStyle !== 'text') rect(xs[i] + 0.5, y - ROW + 0.5, cols[i] - 1, ROW - 1, TONE_RGB[c.tone]);
      const s = fit(c.text, cols[i] - 6, SIZE);
      const align = t.columns[i]?.align ?? 'left';
      const x = align === 'right' ? xs[i] + cols[i] - 3 - width(s, SIZE) : xs[i] + 3;
      text(s, x, y - ROW + 4.5, SIZE, c.tone !== undefined && c.tone !== null && c.toneStyle === 'text', c.tone && c.toneStyle === 'text' ? TONE_INK[c.tone] : undefined);
    });
    y -= ROW;
  });
  if (t.totals) {
    if (y - ROW < M + 20) newPage();
    line(M, y, M + avail, 0.8);
    t.totals.forEach((s0, i) => {
      const s = fit(s0, cols[i] - 6, SIZE, true);
      const x = (t.columns[i]?.align ?? 'left') === 'right' ? xs[i] + cols[i] - 3 - width(s, SIZE, true) : xs[i] + 3;
      text(s, x, y - ROW + 4.5, SIZE, true);
    });
    y -= ROW;
    line(M, y, M + avail, 0.8);
  }
  if (t.note) {
    if (y - 14 < M + 20) newPage();
    text(fit(t.note, avail, 8), M, y - 12, 8, false, [0.28, 0.33, 0.41]);
  }
  pages.push(page);

  // Footers once the page count is known.
  pages.forEach((p, i) => {
    page = p;
    line(M, M + 8, W - M, 0.3);
    text(fit(t.footer, avail - 90, 7), M, M - 2, 7, false, [0.39, 0.45, 0.55]);
    const label = t.pageLabel.replace('{n}', String(i + 1)).replace('{m}', String(pages.length));
    text(label, W - M - width(label, 7), M - 2, 7, false, [0.39, 0.45, 0.55]);
  });

  // Assemble: catalog, pages, base fonts, Indic fonts, then each page and its content stream.
  const objs: Buffer[] = [];
  const add = (body: string) => objs.push(Buffer.from(body, 'latin1'));
  add('<< /Type /Catalog /Pages 2 0 R >>');
  add(`<< /Type /Pages /Kids [${pages.map((_, i) => `${5 + i * 2} 0 R`).join(' ')}] /Count ${pages.length} >>`);
  add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
  add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');
  const indic = fonts.objects(5 + pages.length * 2);
  const fontRes = Object.entries(indic.refs).map(([k, v]) => ` /${k} ${v} 0 R`).join('');
  pages.forEach((p, i) => {
    add(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] /Resources << /Font << /F1 3 0 R /F2 4 0 R${fontRes} >> >> /Contents ${6 + i * 2} 0 R >>`);
    const stream = p.join('\n');
    add(`<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}\nendstream`);
  });
  objs.push(...indic.objs);
  const parts: Buffer[] = [Buffer.from('%PDF-1.4\n', 'latin1')];
  const offsets: number[] = [];
  let pos = parts[0].length;
  objs.forEach((o, i) => {
    offsets.push(pos);
    const b = Buffer.concat([Buffer.from(`${i + 1} 0 obj\n`, 'latin1'), o, Buffer.from('\nendobj\n', 'latin1')]);
    parts.push(b);
    pos += b.length;
  });
  parts.push(Buffer.from(`xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${pos}\n%%EOF\n`, 'latin1'));
  return Buffer.concat(parts);
}
