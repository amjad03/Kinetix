import { toCsv } from '../common/pdf.js';
import type { Cell, Definition, OutColumn, StudioResult } from './engine.js';
import { renderTablePdf } from './report-pdf.js';
import type { Lang } from './semantic.js';
import { buildXlsx, type Tone, type XlsxCell } from './xlsx.js';

/** Turns a report result into a CSV, an XLSX workbook or a landscape PDF with the institution's header. */

export const EXPORT_FORMATS = ['csv', 'xlsx', 'pdf'] as const;
export type ExportFormat = (typeof EXPORT_FORMATS)[number];

export interface ExportMeta {
  institution: string;
  title: string;
  generatedBy: string;
  /** The institution's local date and time. */
  generatedAt: string;
  at: Date;
  lang: Lang;
}

export interface Rendered {
  contentType: string;
  filename: string;
  body: Buffer;
}

const WORDS: Record<Lang, { yes: string; no: string; filters: string; none: string; generated: string; page: string; truncated: string }> = {
  en: { yes: 'Yes', no: 'No', filters: 'Filters', none: 'No filters: every record you may see', generated: 'Generated by {who} on {at} · KINETIX', page: 'Page {n} of {m}', truncated: 'Only the first {n} rows are shown. Narrow the filters to see the rest.' },
  hi: { yes: 'हाँ', no: 'नहीं', filters: 'फ़िल्टर', none: 'कोई फ़िल्टर नहीं: आपको दिखने वाले सभी रिकॉर्ड', generated: '{who} द्वारा {at} को बनाया गया · KINETIX', page: 'पृष्ठ {n} / {m}', truncated: 'केवल पहली {n} पंक्तियाँ दिखाई गई हैं। शेष देखने के लिए फ़िल्टर सीमित करें।' },
  kn: { yes: 'ಹೌದು', no: 'ಇಲ್ಲ', filters: 'ಫಿಲ್ಟರ್‌ಗಳು', none: 'ಫಿಲ್ಟರ್ ಇಲ್ಲ: ನಿಮಗೆ ಕಾಣುವ ಎಲ್ಲಾ ದಾಖಲೆಗಳು', generated: '{who} ಅವರಿಂದ {at} ರಂದು ರಚಿಸಲಾಗಿದೆ · KINETIX', page: 'ಪುಟ {n} / {m}', truncated: 'ಮೊದಲ {n} ಸಾಲುಗಳನ್ನು ಮಾತ್ರ ತೋರಿಸಲಾಗಿದೆ. ಉಳಿದವು ನೋಡಲು ಫಿಲ್ಟರ್ ಕಿರಿದುಗೊಳಿಸಿ.' },
};

const NUMERIC = new Set(['int', 'number', 'money', 'percent']);

/** Indian digit grouping: 12,34,567.89. */
export function indian(n: number, decimals: number): string {
  const neg = n < 0;
  const [int, frac] = Math.abs(n).toFixed(decimals).split('.');
  const last3 = int.slice(-3);
  const rest = int.slice(0, -3).replace(/\B(?=(\d{2})+(?!\d))/g, ',');
  return `${neg ? '-' : ''}${rest ? `${rest},${last3}` : last3}${frac ? `.${frac}` : ''}`;
}

/** A cell as text for the PDF: rupees with grouping, percents with %, yes/no in words. */
export function cellText(c: OutColumn, v: Cell, lang: Lang): string {
  if (v === null || v === undefined || v === '') return '';
  const w = WORDS[lang];
  if (typeof v === 'boolean') return v ? w.yes : w.no;
  if (typeof v === 'number') {
    if (c.type === 'money') return `₹${indian(v / 100, 2)}`;
    if (c.type === 'percent') return `${indian(v, 1)}%`;
    if (c.type === 'int') return indian(v, 0);
    return indian(v, Number.isInteger(v) ? 0 : 2);
  }
  if (c.type === 'date' && /^\d{4}-\d{2}-\d{2}$/.test(v)) {
    const [y, m, d] = v.split('-');
    return `${d}-${['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][Number(m) - 1]}-${y}`;
  }
  return String(v);
}

/** The tone a conditional-formatting rule gives a cell (rules on a measure apply to its pivot columns too). */
export function toneOf(col: OutColumn, v: Cell, rules: Definition['formatting']): { tone: Tone; style: 'fill' | 'text' } | null {
  for (const r of rules) {
    if (r.op === 'bar') continue;
    if (r.column !== col.key && r.column !== col.measure) continue;
    if (v === null || v === undefined) continue;
    const n = typeof v === 'number' ? v : Number(v);
    const val = typeof r.value === 'number' ? r.value : Number(r.value);
    // Money rules are typed in rupees; values are paise.
    const x = col.type === 'money' && typeof v === 'number' ? v / 100 : n;
    let hit = false;
    switch (r.op) {
      case 'gt':
        hit = x > val;
        break;
      case 'gte':
        hit = x >= val;
        break;
      case 'lt':
        hit = x < val;
        break;
      case 'lte':
        hit = x <= val;
        break;
      case 'between':
        hit = x >= val && x <= (r.value2 ?? val);
        break;
      case 'eq':
        hit = typeof r.value === 'number' ? x === val : String(v) === String(r.value);
        break;
      case 'neq':
        hit = typeof r.value === 'number' ? x !== val : String(v) !== String(r.value);
        break;
      case 'contains':
        hit = String(v).toLowerCase().includes(String(r.value ?? '').toLowerCase());
        break;
    }
    if (hit) return { tone: r.tone, style: r.style };
  }
  return null;
}

/** CSV: money in rupees, plain numbers, yes/no in words; formula-looking text is neutralised. */
export function renderResultCsv(res: StudioResult, lang: Lang): Buffer {
  const w = WORDS[lang];
  const cell = (c: OutColumn, v: Cell) => (v === null || v === undefined ? '' : typeof v === 'boolean' ? (v ? w.yes : w.no) : c.type === 'money' && typeof v === 'number' ? (v / 100).toFixed(2) : v);
  const lines = [res.columns.map((c) => c.label), ...res.rows.map((r) => res.columns.map((c) => cell(c, r[c.key] ?? null)))];
  if (res.totals) lines.push(res.columns.map((c) => cell(c, res.totals![c.key] ?? null)));
  return Buffer.from('﻿' + toCsv(lines), 'utf8');
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 60) || 'report';

export function renderResult(res: StudioResult, format: ExportFormat, meta: ExportMeta): Rendered {
  const w = WORDS[meta.lang];
  const base = `${slug(meta.title)}-${meta.generatedAt.slice(0, 10)}`;
  const generated = w.generated.replace('{who}', meta.generatedBy).replace('{at}', meta.generatedAt);
  const filtersLine = res.filters.length ? `${w.filters}: ${res.filters.join(' · ')}` : w.none;
  const note = res.truncated ? w.truncated.replace('{n}', String(res.rows.length)) : undefined;
  if (format === 'csv') return { contentType: 'text/csv; charset=utf-8', filename: `${base}.csv`, body: renderResultCsv(res, meta.lang) };
  if (format === 'xlsx') {
    const cells = (row: Record<string, Cell>, styled: boolean): XlsxCell[] =>
      res.columns.map((c) => {
        const v = row[c.key] ?? null;
        const tone = styled ? toneOf(c, v, res.formatting) : null;
        return { v, type: c.type, tone: tone?.tone ?? null, toneStyle: tone?.style };
      });
    const body = buildXlsx(
      {
        name: meta.title,
        heading: [meta.institution, meta.title, filtersLine, generated, ...(note ? [note] : [])],
        header: res.columns.map((c) => c.label),
        types: res.columns.map((c) => c.type),
        rows: res.rows.map((r) => cells(r, true)),
        totals: res.totals ? cells(res.totals, false) : null,
      },
      { yes: w.yes, no: w.no, creator: meta.generatedBy, at: meta.at },
    );
    return { contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', filename: `${base}.xlsx`, body };
  }
  const body = renderTablePdf({
    institution: meta.institution,
    title: meta.title,
    filters: [filtersLine],
    columns: res.columns.map((c) => ({ label: c.label, align: NUMERIC.has(c.type) ? 'right' : 'left' })),
    rows: res.rows.map((r) =>
      res.columns.map((c) => {
        const v = r[c.key] ?? null;
        const tone = toneOf(c, v, res.formatting);
        return { text: cellText(c, v, meta.lang), tone: tone?.tone ?? null, toneStyle: tone?.style };
      }),
    ),
    totals: res.totals ? res.columns.map((c) => cellText(c, res.totals![c.key] ?? null, meta.lang)) : null,
    footer: generated,
    pageLabel: w.page,
    note,
  });
  return { contentType: 'application/pdf', filename: `${base}.pdf`, body };
}
