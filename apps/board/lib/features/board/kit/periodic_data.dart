/// The block an element's last electron goes into, as the NCERT table shades it.
enum ElementBlock { s, p, d, f }

/// The state of an element at room temperature (25 °C) and normal pressure.
enum MatterState { solid, liquid, gas, unknown }

/// What the periodic table's element sheet shows besides the number, name and mass: the
/// block, the electron configuration and shells, the electronegativity (Pauling), the state
/// at room temperature, the year of discovery, common uses, and the name in Hindi and Kannada.
/// Configurations follow the Aufbau order with the known exceptions (Cr, Cu, Nb, Mo, Ru, Rh,
/// Pd, Ag, La, Ce, Gd, Pt, Au, Ac, Th, Pa, U, Np, Cm), as NCERT's Classes 11 and 12 give them;
/// for Z ≥ 104 they are predicted. Electronegativities and years are the commonly tabulated
/// values (CRC Handbook, IUPAC); 0 means known since ancient times.
extension ChemElementFacts on ChemElement {
  ElementBlock get block {
    if (z == 2 || group <= 2) return ElementBlock.s;
    if (group >= 13) return ElementBlock.p;
    final fRow = (cat == ElementCategory.lanthanide && z != 57) || (cat == ElementCategory.actinide && z != 89);
    return fRow ? ElementBlock.f : ElementBlock.d;
  }

  /// The configuration with its noble-gas core, as "[Ar] 3d⁶ 4s²".
  String get configuration => electronConfiguration(z);

  /// Electrons in each shell (K, L, M, ...), as 2, 8, 14, 2 for iron.
  List<int> get shells => electronShells(z);

  /// Pauling electronegativity, or null where none is known (helium, neon, argon, Z > 103).
  double? get electronegativity => _electronegativity[z - 1];

  MatterState get state => switch (z) {
    1 || 2 || 7 || 8 || 9 || 10 || 17 || 18 || 36 || 54 || 86 => MatterState.gas,
    35 || 80 => MatterState.liquid,
    >= 100 => MatterState.unknown,
    _ => MatterState.solid,
  };

  /// The year it was discovered or first recognised; 0 when known since ancient times.
  int get discovered => _discovered[z - 1];

  /// Whether the configuration is predicted rather than measured (Z ≥ 104).
  bool get predicted => z >= 104;

  /// The name in [lang] ('en', 'hi' or 'kn').
  String nameIn(String lang) => switch (lang) {
    'hi' => _hi[z - 1],
    'kn' => _kn[z - 1],
    _ => name,
  };

  /// Common uses in [lang].
  String usesIn(String lang) => switch (lang) {
    'hi' => _usesHi[z - 1],
    'kn' => _usesKn[z - 1],
    _ => _usesEn[z - 1],
  };

  /// Whether [query] finds this element: its symbol, its number or its name in any language.
  bool matches(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return true;
    if (int.tryParse(q) case final n?) return n == z;
    if (symbol.toLowerCase() == q) return true;
    return name.toLowerCase().contains(q) || _hi[z - 1].contains(q) || _kn[z - 1].contains(q);
  }
}

