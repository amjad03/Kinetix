Map<(int, int), int> _aufbau(int z) {
  final out = <(int, int), int>{};
  var left = z;
  for (final (n, l) in _order) {
    if (left <= 0) break;
    final k = left < 4 * l + 2 ? left : 4 * l + 2;
    out[(n, l)] = k;
    left -= k;
  }
  return out;
}

/// Electrons in each subshell (n, l) of element [z].
Map<(int, int), int> subshells(int z) {
  final ex = _exceptions[z];
  if (ex == null) return _aufbau(z);
  final core = _nobleCores.firstWhere((c) => c.$1 < z);
  final out = _aufbau(core.$1);
  for (final part in ex.split(' ')) {
    final m = RegExp(r'^(\d)([spdf])(\d+)$').firstMatch(part)!;
    out[(int.parse(m[1]!), _letters.indexOf(m[2]!))] = int.parse(m[3]!);
  }
  return out;
}

const _sup = ['⁰', '¹', '²', '³', '⁴', '⁵', '⁶', '⁷', '⁸', '⁹'];
String _superscript(int n) => '$n'.split('').map((d) => _sup[int.parse(d)]).join();

/// "[Ar] 3d⁶ 4s²" for iron: the noble-gas core, then the other subshells by shell and type.
String electronConfiguration(int z) {
  final all = subshells(z);
  final core = z <= 2 ? null : _nobleCores.firstWhere((c) => c.$1 < z);
  final inCore = core == null ? const <(int, int), int>{} : _aufbau(core.$1);
  final outer = [
    for (final e in all.entries)
      if (e.value > 0 && inCore[e.key] != e.value) e,
  ]..sort((a, b) => a.key.$1 != b.key.$1 ? a.key.$1.compareTo(b.key.$1) : a.key.$2.compareTo(b.key.$2));
  final parts = [for (final e in outer) '${e.key.$1}${_letters[e.key.$2]}${_superscript(e.value)}'];
  return [if (core != null) '[${core.$2}]', ...parts].join(' ');
}

/// Electrons per shell, K first.
List<int> electronShells(int z) {
  final all = subshells(z);
  final top = all.keys.map((k) => k.$1).reduce((a, b) => a > b ? a : b);
  return [
    for (var n = 1; n <= top; n++) all.entries.where((e) => e.key.$1 == n).fold(0, (s, e) => s + e.value),
  ];
}

