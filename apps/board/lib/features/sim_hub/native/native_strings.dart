/// The native sims' own words (Stroop, reaction time, memory span, the money model, the
/// key-dates timeline, grammar check, map lab and map quiz) in English, Hindi and Kannada.
class NativeSimStrings {
  NativeSimStrings(String lang) : _s = FeatureStrings(lang, nativeSimStringTable);

  factory NativeSimStrings.of(BuildContext context) => NativeSimStrings(boardLang(context));

  final FeatureStrings _s;

  String get lang => _s.lang;

  String operator [](String key) => _s[key];

  /// [key] with each `{name}` replaced by its value in [args].
  String f(String key, Map<String, Object> args) {
    var t = _s[key];
    for (final e in args.entries) {
      t = t.replaceAll('{${e.key}}', '${e.value}');
    }
    return t;
  }

  /// A Stroop colour's word ('RED' → लाल).
  String colour(String name) => _s['colour$name'];

  /// A map quiz place's name.
  String place(String name) => (nativeSimPlaces[name]?[_s.lang]) ?? name;
}

