import 'dart:typed_data';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:kinetix_student/core/live.dart';

import 'fake_api.dart';
import 'fake_live.dart';
import 'helpers.dart';

/// Seeing the teacher's camera beside the board in a live (hybrid) class.
void main() {
  const device = '11111111-2222-3333-4444-555555555555';

  Future<void> settle(WidgetTester tester) async {
    for (var i = 0; i < 8; i++) {
      await tester.pump(const Duration(milliseconds: 100));
    }
  }

  /// A 1×1 JPEG.
  final jpeg = Uint8List.fromList(const [
    0xFF, 0xD8, 0xFF, 0xDB, 0x00, 0x43, 0x00, 0x08, 0x06, 0x06, 0x07, 0x06, 0x05, 0x08, 0x07, 0x07, 0x07, 0x09, 0x09, 0x08, 0x0A, 0x0C, 0x14, 0x0D, //
    0x0C, 0x0B, 0x0B, 0x0C, 0x19, 0x12, 0x13, 0x0F, 0x14, 0x1D, 0x1A, 0x1F, 0x1E, 0x1D, 0x1A, 0x1C, 0x1C, 0x20, 0x24, 0x2E, 0x27, 0x20, 0x22, 0x2C,
    0x23, 0x1C, 0x1C, 0x28, 0x37, 0x29, 0x2C, 0x30, 0x31, 0x34, 0x34, 0x34, 0x1F, 0x27, 0x39, 0x3D, 0x38, 0x32, 0x3C, 0x2E, 0x33, 0x34, 0x32, 0xFF,
    0xC0, 0x00, 0x0B, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00, 0xFF, 0xC4, 0x00, 0x14, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x09, 0xFF, 0xC4, 0x00, 0x14, 0x10, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xDA, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3F, 0x00, 0x2A, 0x9F, 0xFF, 0xD9,
  ]);

  testWidgets('the teacher camera shows beside the board while it is on', (tester) async {
    final server = FakeLiveServer()..ack = const LiveWatchAck(ok: true, teacher: 'Anita Sharma', subject: 'Corporate Accounting', audioAllowed: true);
    await pumpApp(tester, live: server, setup: (api) => api.liveClass = FakeStudentApi.corporateLive());
    await tester.ensureVisible(find.byKey(const Key('watchLive')));
    await tester.pumpAndSettle();
    await tester.tap(find.byKey(const Key('watchLive')));
    await settle(tester);
    final conn = server.last;
    conn.send(const LiveFrame(device, [
      [0, 'L', [<dynamic>[]], 0],
    ]));
    await settle(tester);
    expect(find.byKey(const Key('liveCamera')), findsNothing);

    conn.send(LiveCameraFrame(device, 0, jpeg));
    conn.send(LiveCameraFrame('99999999-2222-3333-4444-555555555555', 0, jpeg)); // another board
    await settle(tester);
    expect(find.byKey(const Key('liveCamera')), findsOneWidget);

    conn.send(const LiveCameraState(device, false));
    await settle(tester);
    expect(find.byKey(const Key('liveCamera')), findsNothing);
  });
}
